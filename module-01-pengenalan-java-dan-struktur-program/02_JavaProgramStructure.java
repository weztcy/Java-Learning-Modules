// Struktur dasar sebuah program Java yang terdiri dari class, method utama, dan statements.
class JavaProgramStructure {
    // Method main dieksekusi secara otomatis saat program dijalankan
    public static void main(String[] args) {
        // Statement pertama: Menampilkan judul materi
        System.out.println("=== Struktur Dasar Program Java ===");
        
        // Statement kedua: Mendemonstrasikan bahwa instruksi dijalankan berurutan dari atas ke bawah
        System.out.println("1. Definisi Class: Membungkus seluruh kode dalam Java");
        System.out.println("2. Method Main: Titik masuk eksekusi JVM");
        System.out.println("3. Statements: Perintah yang diakhiri tanda titik koma (;)");
    }
}
