// Mendemonstrasikan pencetakan teks yang otomatis berpindah ke baris berikutnya.
class SystemOutPrintln {
    public static void main(String[] args) {
        // Setiap pemanggilan println akan mencetak teks lalu menyisipkan karakter baris baru (newline)
        System.out.println("Baris 1: Belajar Java sangat menyenangkan.");
        System.out.println("Baris 2: Setiap println otomatis membuat baris baru.");
        System.out.println("Baris 3: Teks ini tercetak di baris ketiga.");
    }
}
